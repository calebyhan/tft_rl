"""Invariants over the live Set 17 dataset in ``data/`` (milestone 8).

Unlike the rest of the suite -- which pins hand-calculated numbers against the
frozen starter fixture -- these tests run against data regenerated by
``scripts/fetch_cdragon.py``. That data changes with every balance patch, so
nothing here asserts a specific stat. It asserts the properties a swap must
preserve: the data loads, references resolve, the pool conserves, combat stays
deterministic and a full match still terminates.

If one of these fails after a re-fetch, the normaliser needs work -- not the
expected value.
"""

from __future__ import annotations

import json

import pytest

from engine.loader import load_all
from engine.match import Match
from engine.schema import ROLES, STAR_LEVELS
from engine.shop import SharedPool
from rl.opponents import GreedyPolicy
from tests.paths import REAL_DATA_DIR


@pytest.fixture(scope="module")
def data():
    return load_all(REAL_DATA_DIR)


def _match(data, seed: int) -> Match:
    # Each seat's policy must be seeded too -- GreedyPolicy() with no seed
    # draws from OS entropy, which would make the match irreproducible even
    # though the engine itself is deterministic.
    players = data.config.round_structure.players
    policies = [GreedyPolicy(seed=seed * 100 + i) for i in range(players)]
    return Match(data, policies, seed=seed)


# --------------------------------------------------------------------------
# Shape
# --------------------------------------------------------------------------


def test_dataset_loads_and_is_a_full_set(data):
    """A partial parse is the classic fetch-script failure; catch it by size."""
    assert len(data.champions) >= 40, "suspiciously few champions -- parser misconfigured?"
    assert len(data.traits) >= 20
    assert len(data.items) >= 20


def test_version_records_a_real_source(data):
    version = json.loads((REAL_DATA_DIR / "VERSION.json").read_text())
    assert version["set"] == 17
    assert "communitydragon.org" in version["source"], "data/ is still the starter sample"


def test_every_shop_cost_tier_is_populated(data):
    """An empty tier would make the shop unable to fill a slot at that cost."""
    by_cost = {}
    for champ in data.champions.values():
        by_cost.setdefault(champ.cost, []).append(champ.id)
    assert sorted(by_cost) == [1, 2, 3, 4, 5]
    for cost, ids in by_cost.items():
        assert len(ids) >= 2, f"cost {cost} has only {ids}"


def test_all_roles_used_are_modelled(data):
    used = {c.role for c in data.champions.values()}
    assert used <= set(ROLES)
    assert len(used) >= 3, "role mapping collapsed too much"


# --------------------------------------------------------------------------
# Referential integrity
