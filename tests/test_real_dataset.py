def test_shared_pool_matches_declared_sizes(data):
    pool = SharedPool(data)
    for champ in data.champions.values():
        expected = data.config.pool_sizes[champ.cost]
        assert pool.remaining(champ.id) == expected


@pytest.mark.parametrize("seed", [0, 1, 2])
def test_a_full_match_terminates_and_conserves_the_pool(data, seed):
    result = _match(data, seed).run()
    assert len(result.placements) == data.config.round_structure.players
    assert sorted(result.placements.values()) == list(
        range(1, data.config.round_structure.players + 1)
    )


def test_combat_is_deterministic_for_a_fixed_seed(data):
    """The core guarantee the whole RL setup rests on."""
    first = _match(data, 7).run()
    second = _match(data, 7).run()
    assert first.placements == second.placements


def test_unimplemented_effects_do_not_crash_a_match(data):
    """Real data declares effect_ids we have not written yet (doc 02 sec 2).

    The whole point of the registry indirection is that this degrades to
    auto-attacks instead of raising.
    """
    unimplemented = [
        c.ability.effect_id
        for c in data.champions.values()
        if c.ability and c.ability.effect_id
    ]
    assert unimplemented, "expected real abilities to be declared but unimplemented"
    _match(data, 11).run()  # must not raise
