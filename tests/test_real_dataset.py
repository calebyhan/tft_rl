def test_every_champion_trait_resolves(data):
    for champ in data.champions.values():
        assert champ.traits, f"{champ.id} has no traits"
        for trait_id in champ.traits:
            assert trait_id in data.traits, f"{champ.id} -> unknown trait {trait_id}"


def test_every_recipe_component_exists_and_is_a_component(data):
    for item in data.items.values():
        for part in item.recipe:
            assert part in data.items, f"{item.id} -> unknown component {part}"
            assert data.items[part].is_component, f"{item.id} -> {part} is not a component"


def test_every_emblem_names_a_real_trait(data):
    emblems = [i for i in data.items.values() if i.category == "emblem"]
    assert emblems, "no emblems were normalised"
    for item in emblems:
        assert item.effect_id and item.effect_id.startswith("emblem_")
        assert item.effect_id[len("emblem_"):] in data.traits


def test_per_star_stats_have_one_entry_per_star(data):
    for champ in data.champions.values():
        assert len(champ.stats.health) == STAR_LEVELS
        assert len(champ.stats.attack_damage) == STAR_LEVELS
        assert champ.stats.health[0] > 0 and champ.stats.attack_damage[0] > 0
        assert champ.stats.max_mana >= 1


def test_star_scaling_is_monotonic(data):
    for champ in data.champions.values():
        assert champ.stats.health[0] < champ.stats.health[1] < champ.stats.health[2]
        assert (
            champ.stats.attack_damage[0]
            < champ.stats.attack_damage[1]
            < champ.stats.attack_damage[2]
        )


def test_ability_per_star_params_are_well_formed(data):
    for champ in data.champions.values():
        if champ.ability is None:
            continue
        for key, value in champ.ability.params.items():
            if isinstance(value, list):
                assert len(value) == STAR_LEVELS, f"{champ.id}.{key}"


